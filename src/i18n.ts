export type Dict = typeof COPY.ar;
export function tr(lang: Lang) {
  return (key: keyof Dict | string): string => {
    const lookup = (src: Record<string, unknown>): string | undefined => {
      const flat = src[key];
      if (typeof flat === 'string') return flat;
      const nested = key.split('.').reduce<unknown>((node, part) =>
        node !== null && typeof node === 'object' ? (node as Record<string, unknown>)[part] : undefined, src);
      return typeof nested === 'string' ? nested : undefined;
    };
    return lookup(COPY[lang] as Record<string, unknown>)
      ?? lookup(COPY.en as Record<string, unknown>)
      ?? key;
  };
}
